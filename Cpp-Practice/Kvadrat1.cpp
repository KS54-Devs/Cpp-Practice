#include <iostream>
#include <cstdlib>

using namespace std;

int main()
{
    system("chcp 65001>nul");

    int n = 0;      // Число, до которого считаем (вводит пользователь)
    int limit = 0;  // Копия числа n, чтобы потом вывести его на экран
    int s = 0;      // Сумма квадратов (сначала 0)

    cout << "Введите верхнюю границу :";
    cin >> n;
    limit = n;      // Запоминаем число, потому что n дальше будет уменьшаться

    // Считаем сумму квадратов: n*n + (n-1)*(n-1) + ... + 1*1
    while (n > 0) {
        s += n * n; // Прибавляем квадрат текущего числа
        n--;        // Переходим к следующему числу (на 1 меньше)
    }

    // Результат
    cout << "Сумма квадратов от 1 до " << limit << " : " << s << "\n";
    system("pause>nul");
}
