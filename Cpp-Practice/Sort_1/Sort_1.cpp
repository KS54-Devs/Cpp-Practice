//Программа сортировки одномерного массива
#include <iostream>
#include <cstdlib>
#include "Sort_1.h"

int main() {
    system("chcp 65001>nul");
    const int n = 10;   // Размер массива
    srand(2);           // Генератор случайных чисел (число 2 - начальное значение)
    int nums[n];        // Массив чисел
    int i, j, k;        // Счётчики для циклов

    cout << "Массив до сортировки :\n";
    // Заполняем массив случайными числами от 0 до 9 и сразу выводим
    for (k = 0; k < n; k++) {
        nums[k] = rand() % 10;
        cout << nums[k] << " ";
    }

    cout << "\nМассив после сортировки :\n";
    // Сортировка пузырьком: сравниваем соседние числа
    // и меняем их местами, если левое больше правого
    for (i = 1; i <= n - 1; i++)
        for (j = 0; j < n - i; j++)
            if (nums[j] > nums[j + 1])
                swap(nums[j], nums[j + 1]); // Функция swap лежит в файле Swap.cpp

    // Отобразить отсортированный массив
    for (k = 0; k < n; k++)
        cout << nums[k] << " ";

    system("pause>nul");
    return 0;
}
